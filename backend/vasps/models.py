from django.db import models


class VASP(models.Model):
    """
    Represents a known Virtual Asset Service Provider (Exchange, Custodian, OTC desk, Payment processor).
    Contains no hardcoded addresses or entities; manageable via Django Admin and authenticated APIs.
    """
    STATUS_CHOICES = (
        ('ACTIVE', 'Active'),
        ('INACTIVE', 'Inactive'),
        ('UNKNOWN', 'Unknown'),
        ('SANCTIONED', 'Sanctioned'),
        ('DEFUNCT', 'Defunct'),
        ('HIGH_RISK', 'High Risk Entity'),
    )

    name = models.CharField(max_length=255, unique=True, db_index=True)
    description = models.TextField(blank=True, default='')
    website = models.URLField(blank=True, default='')
    jurisdiction = models.CharField(max_length=100, blank=True, default='')
    status = models.CharField(max_length=20, choices=STATUS_CHOICES, default='ACTIVE', db_index=True)
    source = models.CharField(max_length=255, blank=True, default='Manual Operator Intelligence')

    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ['name']
        verbose_name = 'VASP'
        verbose_name_plural = 'VASPs'
        indexes = [
            models.Index(fields=['name']),
            models.Index(fields=['status']),
            models.Index(fields=['created_at']),
        ]

    def save(self, *args, **kwargs):
        if self.status:
            self.status = self.status.upper()
        super().save(*args, **kwargs)

    def __str__(self):
        return f"{self.name} ({self.status})"


class VASPAddress(models.Model):
    """
    Known wallet address associated with a VASP entity (deposit addresses, hot wallets, sweeps).
    Managed by administrators and intelligence ingestion.
    """
    ADDRESS_TYPE_CHOICES = (
        ('hot_wallet', 'Hot Wallet / Main Cluster'),
        ('deposit_address', 'Customer Deposit Address'),
        ('cold_storage', 'Cold Storage Reserve'),
        ('sweep_account', 'Sweeper / Aggregator'),
        ('fee_collector', 'Fee Collector / Gas Tank'),
        ('other', 'Other Known Infrastructure'),
    )

    vasp = models.ForeignKey(VASP, related_name='known_addresses', on_delete=models.CASCADE)
    address = models.CharField(max_length=128, db_index=True)
    blockchain = models.CharField(max_length=32, default='ethereum', db_index=True)

    address_type = models.CharField(
        max_length=50,
        default='hot_wallet',
        choices=ADDRESS_TYPE_CHOICES
    )
    label = models.CharField(max_length=255, blank=True, default='')
    source = models.CharField(max_length=255, blank=True, default='Manual Intelligence')
    confidence = models.FloatField(default=1.0)  # 0.0 to 1.0 confidence in address attribution

    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        constraints = [
            models.UniqueConstraint(
                fields=['address', 'blockchain'],
                name='unique_vasp_address_per_blockchain'
            )
        ]
        indexes = [
            models.Index(fields=['address']),
            models.Index(fields=['blockchain']),
            models.Index(fields=['address', 'blockchain']),
            models.Index(fields=['address_type']),
            models.Index(fields=['vasp', 'confidence']),
        ]
        verbose_name = 'VASP Address'
        verbose_name_plural = 'VASP Addresses'

    def save(self, *args, **kwargs):
        if self.address:
            self.address = self.address.strip()
            if self.blockchain in ('ethereum', 'polygon', 'arbitrum', 'optimism', 'base', 'binance-smart-chain'):
                self.address = self.address.lower()
        super().save(*args, **kwargs)

    def __str__(self):
        return f"{self.vasp.name} - {self.address} ({self.address_type})"


class VASPAttribution(models.Model):
    """
    Attribution result generated by the analysis engine linking a wallet or investigation to a candidate VASP.
    Stores dynamically computed score, confidence, rank, and structured evidence.
    """
    CONFIDENCE_CHOICES = (
        ('high', 'High Confidence'),
        ('medium', 'Medium Confidence'),
        ('low', 'Low Confidence'),
    )

    investigation = models.ForeignKey(
        'investigations.Investigation',
        related_name='attributions',
        on_delete=models.CASCADE,
        null=True,
        blank=True
    )
    wallet = models.ForeignKey(
        'wallets.Wallet',
        related_name='vasp_attributions',
        on_delete=models.CASCADE,
        null=True,
        blank=True
    )
    vasp = models.ForeignKey(VASP, related_name='attributions', on_delete=models.CASCADE)

    score = models.FloatField(default=0.0)  # Calculated dynamically by analysis engine
    confidence = models.CharField(
        max_length=20,
        default='medium',
        choices=CONFIDENCE_CHOICES
    )
    rank = models.PositiveSmallIntegerField(default=1)

    # Detailed explainable evidence dictionary from actual graph and fund flow analysis:
    # {
    #   "direct_interactions": 0,
    #   "hop_distance": 1,
    #   "interaction_count": 4,
    #   "fund_flow_connection": true,
    #   "signals": {...}
    # }
    evidence = models.JSONField(default=dict, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ['rank', '-score']
        indexes = [
            models.Index(fields=['investigation', 'rank']),
            models.Index(fields=['investigation', 'vasp']),
            models.Index(fields=['score']),
            models.Index(fields=['created_at']),
        ]

    def __str__(self):
        return f"Rank #{self.rank}: {self.vasp.name} ({self.score:.1f}% confidence)"

